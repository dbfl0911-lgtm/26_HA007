def trip_attraction(h: int, dow: int = 0) -> dict[str, float]:
    """이 시각에 '승객이 가고 싶어 하는' 목적지 가중치(정왕동 생활권 기준)."""
    h %= 24
    dow %= 7
    weekend = dow >= 5
    w: dict[str, float] = {}

    if h >= 21 or h <= 1:  # 저녁~심야: 술자리로 이동(금·토 폭증)
        party = 9.0 if dow == 4 else 7.0 if dow == 5 else 3.5
        w = {"정왕동 먹자골목": party, "정왕역": 2.0, "성담스퀘어": 1.5}
    elif 7 <= h <= 9 and not weekend:  # 출근: 직장·학교로 유입
        w = {"시화국가산업단지": 6.0, "한국공학대학교": 4.5, "정왕고등학교": 2.0,
             "시흥중앙도서관": 1.5}
    elif 17 <= h <= 20 and not weekend:  # 퇴근: 역·주거지로, 금요일은 회식 상권으로
        w = {"정왕역": 4.0, "성담스퀘어": 2.5, "정왕본동 행정복지센터": 2.0,
             "정왕전통시장": 1.5}
        if dow == 4:
            w.update({"정왕동 먹자골목": 7.0})
    elif 10 <= h <= 16:  # 주간: 상권·생활
        w = {"성담스퀘어": 3.0, "정왕전통시장": 2.5, "시흥중앙도서관": 2.0,
             "시화병원": 1.8, "정왕역": 1.5}
    return w
