def hotspots_for_hour(h: int, dow: int = 0) -> list[tuple[str, float]]:
    """시간대(+요일)별 수요 핫스팟."""
    h %= 24
    dow %= 7
    weekend = dow >= 5

    # 저녁~심야 유흥(21~01시)
    if h >= 21 or h <= 1:
        party = 8.0 if dow == 4 else 6.5 if dow == 5 else 3.5  # 금 > 토 > 평일
        return [("정왕동 먹자골목", party), ("정왕역", 2.0), ("성담스퀘어", 1.2)]

    # 출근(평일)
    if 7 <= h <= 9 and not weekend:
        return [("시화국가산업단지", 4.0), ("한국공학대학교", 3.5), ("정왕역", 3.0)]

    # 퇴근(평일)
    if 17 <= h <= 20 and not weekend:
        if dow == 4:
            return [("정왕역", 3.0), ("시화국가산업단지", 2.5), ("한국공학대학교", 1.5),
                    ("정왕동 먹자골목", 4.5), ("성담스퀘어", 2.0)]
        return [("정왕역", 3.5), ("시화국가산업단지", 3.0), ("한국공학대학교", 2.0),
                ("성담스퀘어", 2.0)]

    # 주간 생활 수요
    if 7 <= h <= 20:
        return [("성담스퀘어", 2.5), ("정왕전통시장", 2.0), ("시흥중앙도서관", 1.5),
                ("정왕역", 1.5), ("한국공학대학교", 1.2)]
    return []


